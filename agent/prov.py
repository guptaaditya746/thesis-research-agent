"""PROV-O export of one run (milestones-1-2.md, row 2.7; provenance-model.md, edge table).

events.jsonl + claims.jsonl + graph.json (+ answer.json when present) -> runs/<id>/graph.ttl.
The chain is verified first; a broken chain is not exported.

Edge table, as exported:

| Link                                   | LEDGER     | Turtle                                                   |
|----------------------------------------|------------|----------------------------------------------------------|
| model call -> command it emitted        | informs    | command prov:wasInformedBy call (any parent_task_id)     |
| command -> corpus file it read          | uses       | command prov:used file (used.files_read / used.files)    |
| claim -> step that made it              | produces   | claim prov:wasGeneratedBy the step's command              |
| anchor -> claim                         | supports   | claim prov:wasDerivedFrom anchor                          |
| broker check of the anchor -> claim     | checked_by | claim ours:checkedBy check; check is a prov:Activity      |
| subagent -> parent agent                | -          | child prov:actedOnBehalfOf parent (from spawn records)    |
| every activity -> its agent             | -          | activity prov:wasAssociatedWith agent                     |
| KG edge -> claim                        | -          | edge prov:wasDerivedFrom claim                            |

Activities are the records of events.jsonl, one IRI per task id. The "step" a claim came from is
the agent_tool record (the command) of the claim's agent and step id, written after the command
ended; failing that the step's model call, failing that a bare step activity. The check of a claim
is the claim record itself (the broker's anchor check: file hash and match), associated with the
claimant and with the broker.

Attach step (2.5): records whose custom_metadata.origin is "attach" (the broker's key on attach
claims; the broker has no attach subtype) get ours:phase "attach" and are dcterms:isPartOf one
attach activity per run. Attach claims are generated by an attach-step command and are
prov:wasInfluencedBy that attach activity, so walking back from them ends at the attach step.

Anchors use the W3C Web Annotation vocabulary: an oa:SpecificResource on the corpus file with an
oa:TextQuoteSelector (exact, prefix, suffix) and an oa:TextPositionSelector (start, end).

The answer (answer.json) is prov:wasGeneratedBy what made it, named by ours:answerSource
(agent/loop.py): `final_answer`, the main agent's model call marked custom_metadata.final_answer;
`draft`, no such call: the harness took the agent's draft file (the `answer_from_draft` coverage
record, which prov:used an ours:AnswerDraft entity carrying the draft's sha256 and the name of
the copy the harness kept, answer.draft.json, and the answer prov:wasDerivedFrom it); `none`, an
answer with no rows (the `no_final_answer` coverage record). A run with none of these records
(built by hand) gets answerSource `unknown` and no such link. After an attach step, answer.json
is generated by the attach activity and derived from an `answer-research` entity
(answer.research.json), which takes the links above; both carry the research answer's source.

IRIs are fixed by the run id and the record, claim, edge and fact ids, so the same run always
exports the same triples, and rdflib's Turtle serialiser sorts subjects and predicates.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any
from urllib.parse import quote

from rdflib import RDF, RDFS, XSD, Graph, Literal, Namespace, URIRef
from rdflib.namespace import DCTERMS, PROV

from . import kg
from .canonical import canonical
from .chain import verify
from .rundir import ANSWER_BEFORE, ATTACH_FILE, RunDir

TTL_FILE = "graph.ttl"
ROOT = "urn:thesis-agent:"
OURS = Namespace(kg.NAMESPACES["ours"])
OA = Namespace("http://www.w3.org/ns/oa#")
CSKG = Namespace(kg.NAMESPACES["cskg"])
DBLP = Namespace(kg.NAMESPACES["dblp"])

CLASSES = {"ai_model_invocation": OURS.ModelInvocation, "agent_tool": OURS.ToolExecution,
           "claim": OURS.ClaimCheck, "spawn": OURS.Spawn, "coverage": OURS.Coverage,
           "concept_pick": OURS.ConceptPick}


def run_base(run_id: str) -> str:
    return f"{ROOT}run:{quote(run_id, safe='')}/"


def corpus_file(name: str) -> URIRef:
    return URIRef(f"{ROOT}corpus/{quote(name, safe='')}")


def node_iri(node_id: str) -> URIRef:
    """graph.json node id (`paper:p3`, `entity:hotpotqa`) -> a run-independent IRI."""
    kind, key = node_id.split(":", 1)
    return URIRef(f"{ROOT}{kind}/{quote(key, safe='-')}")


class Iris:
    def __init__(self, run_id: str) -> None:
        self.base = run_base(run_id)

    def __call__(self, *parts: str) -> URIRef:
        return URIRef(self.base + "/".join(quote(p, safe="-") for p in parts))


def _lines(path: Path) -> list[dict[str, Any]]:
    return [json.loads(raw) for raw in path.read_text(encoding="utf-8").splitlines()] if path.exists() else []


def _json(value: Any) -> Literal:
    return Literal(canonical(value))


def _value(value: Any) -> Literal:
    """A claim's or fact's o: string, integer, number or boolean keeps its XSD type."""
    return Literal(value)


def _is_attach(record: dict[str, Any]) -> bool:
    return record.get("custom_metadata", {}).get("origin") == "attach"


def files_read(used: dict[str, Any]) -> list[str]:
    files = used.get("files_read", used.get("files", []))
    return sorted({Path(str(f).replace("\\", "/")).name for f in files}) if isinstance(files, list) else []


def build(run: RunDir) -> Graph:
    report = verify(run.events, run.claims)
    if not report.ok:
        raise ValueError(f"refusing to export a broken chain: {report.errors}")
    graph_path = run.root / kg.GRAPH_FILE
    if not graph_path.is_file():
        raise FileNotFoundError(f"{graph_path} is missing; run `agent graph` first")
    kgraph = kg.load(run)
    config = run.load_config()
    records = _lines(run.events)
    iri = Iris(run.run_id)
    g = Graph(bind_namespaces="core")
    for prefix, ns in (("prov", PROV), ("oa", OA), ("ours", OURS), ("cskg", CSKG), ("dblp", DBLP),
                       ("dcterms", DCTERMS), ("xsd", XSD), ("rdfs", RDFS)):
        g.bind(prefix, ns)
    g.bind("run", Namespace(iri.base))

    run_node = iri("run")
    g.add((run_node, RDF.type, PROV.Activity))
    g.add((run_node, RDF.type, OURS.Run))
    g.add((run_node, OURS.runId, Literal(run.run_id)))
    g.add((run_node, OURS.condition, Literal(config["condition"])))
    g.add((run_node, OURS.configJson, _json(config)))
    g.add((run_node, OURS.chainHead, Literal(report.head)))

    broker = iri("agent", "broker")
    g.add((broker, RDF.type, PROV.SoftwareAgent))
    g.add((broker, RDFS.label, Literal("provenance broker (agent/broker.py)")))
    agents: set[str] = set()

    def agent(agent_id: str) -> URIRef:
        node = iri("agent", agent_id)
        if agent_id not in agents:
            agents.add(agent_id)
            g.add((node, RDF.type, PROV.SoftwareAgent))
            g.add((node, OURS.agentId, Literal(agent_id)))
        return node

    model = config["models"]["orchestrator"]
    g.add((agent("main"), OURS.model, Literal(f"{model['name']}@{model['revision']}")))
    g.add((run_node, PROV.wasAssociatedWith, agent("main")))

    attach = iri("activity", "attach")
    attach_times: list[str] = []
    tools: dict[tuple[str, int], list[tuple[int, URIRef]]] = {}
    calls: dict[tuple[str, int], list[tuple[int, URIRef]]] = {}
    claims: dict[str, URIRef] = {}

    for n, rec in enumerate(records):
        act = iri("task", rec["task_id"])
        sub = rec["subtype"]
        for t in (PROV.Activity, CLASSES[sub]):
            g.add((act, RDF.type, t))
        g.add((act, OURS.taskId, Literal(rec["task_id"])))
        g.add((act, OURS.subtype, Literal(sub)))
        g.add((act, OURS.stepId, Literal(rec["step_id"])))
        g.add((act, OURS.groupId, Literal(rec["group_id"])))
        g.add((act, OURS.status, Literal(rec["status"])))
        g.add((act, OURS.recordHash, Literal(rec["hash"])))
        g.add((act, PROV.startedAtTime, Literal(rec["started_at"], datatype=XSD.dateTime)))
        g.add((act, PROV.endedAtTime, Literal(rec["ended_at"], datatype=XSD.dateTime)))
        g.add((act, DCTERMS.isPartOf, run_node))
        g.add((act, PROV.wasAssociatedWith, agent(rec["agent_id"])))  # every activity -> its agent
        if rec["source_agent_id"]:
            g.add((act, OURS.sourceAgent, agent(rec["source_agent_id"])))
        if rec["parent_task_id"]:  # informs
            g.add((act, PROV.wasInformedBy, iri("task", rec["parent_task_id"])))
        if rec["custom_metadata"] and sub != "claim":
            g.add((act, OURS.metadataJson, _json(rec["custom_metadata"])))
        phase = "attach" if _is_attach(rec) else "research"
        g.add((act, OURS.phase, Literal(phase)))
        if phase == "attach":
            g.add((act, DCTERMS.isPartOf, attach))
            attach_times += [rec["started_at"], rec["ended_at"]]
        used, generated = rec["used"], rec["generated"]
        key = (rec["agent_id"], rec["step_id"])
        if sub == "ai_model_invocation":
            calls.setdefault(key, []).append((n, act))
            for field, prop in (("model", OURS.model), ("revision", OURS.modelRevision),
                                ("temperature", OURS.temperature), ("seed", OURS.seed),
                                ("prompt_sha256", OURS.promptSha256)):
                if field in used:
                    g.add((act, prop, Literal(used[field])))
            if "response_sha256" in generated:
                g.add((act, OURS.responseSha256, Literal(generated["response_sha256"])))
        elif sub == "agent_tool":
            tools.setdefault(key, []).append((n, act))
            if "command" in used:
                g.add((act, OURS.command, Literal(used["command"])))
            for name in files_read(used):  # uses
                g.add((act, PROV.used, corpus_file(name)))
                g.add((corpus_file(name), RDF.type, OURS.CorpusFile))
        elif sub == "spawn" and isinstance(generated.get("agent_id"), str):
            child = agent(generated["agent_id"])
            g.add((child, PROV.actedOnBehalfOf, agent(rec["agent_id"])))
            g.add((act, OURS.spawnedAgent, child))
            if "model_name" in generated:  # a subagent's start record names its sub-model (row 2.12)
                g.add((child, OURS.model, Literal(f"{generated['model_name']}@{generated.get('revision', '')}")))
        if sub != "claim":
            g.add((act, OURS.usedJson, _json(used)))
            g.add((act, OURS.generatedJson, _json(generated)))

    def step_of(n: int, key: tuple[str, int]) -> URIRef:
        """The command the claim was sent from; else the step's model call; else a bare step."""
        for table in (tools, calls):
            found = table.get(key, [])
            later = [a for i, a in found if i > n]
            if later or found:
                return (later or [found[-1][1]])[0]
        step = iri("step", key[0], str(key[1]))
        g.add((step, RDF.type, PROV.Activity))
        g.add((step, OURS.stepId, Literal(key[1])))
        g.add((step, PROV.wasAssociatedWith, agent(key[0])))
        return step

    for n, rec in enumerate(records):
        if rec["subtype"] != "claim":
            continue
        check = iri("task", rec["task_id"])
        meta = rec["custom_metadata"]
        g.add((check, PROV.wasAssociatedWith, broker))
        g.add((check, OURS.origin, Literal(meta.get("origin", "research"))))
        for field in ("s", "p", "o"):
            if field in meta:
                g.add((check, OURS[field], _value(meta[field])))
        if rec["status"] != "accepted":
            g.add((check, OURS.reason, Literal(meta.get("reason", ""))))
            g.add((check, OURS.usedJson, _json(rec["used"])))
            continue
        claim_id = rec["generated"]["claim_id"]
        claim = iri("claim", claim_id)
        claims[claim_id] = claim
        sel = rec["used"]["anchor"]
        anchor = iri("anchor", claim_id)
        quote_sel, pos_sel = iri("anchor", claim_id, "quote"), iri("anchor", claim_id, "position")
        source = corpus_file(sel["file"])
        g.add((claim, RDF.type, PROV.Entity))
        g.add((claim, RDF.type, OURS.Claim))
        g.add((claim, OURS.claimId, Literal(claim_id)))
        g.add((claim, OURS.origin, Literal(meta.get("origin", "research"))))
        for field in ("s", "p", "o"):
            g.add((claim, OURS[field], _value(meta[field])))
        step = step_of(n, (rec["agent_id"], rec["step_id"]))
        g.add((claim, PROV.wasGeneratedBy, step))  # produces
        g.add((claim, PROV.wasDerivedFrom, anchor))  # supports
        g.add((claim, OURS.checkedBy, check))  # checked_by
        g.add((check, PROV.used, anchor))
        g.add((check, PROV.used, source))
        g.add((check, PROV.generated, claim))
        if meta.get("origin") == "attach":
            g.add((claim, PROV.wasInfluencedBy, attach))
        g.add((anchor, RDF.type, PROV.Entity))
        g.add((anchor, RDF.type, OA.SpecificResource))
        g.add((anchor, OA.hasSource, source))
        g.add((anchor, OA.hasSelector, quote_sel))
        g.add((anchor, OA.hasSelector, pos_sel))
        g.add((anchor, OURS.sha256, Literal(sel["sha256"])))
        g.add((source, RDF.type, OURS.CorpusFile))
        g.add((source, OURS.fileName, Literal(sel["file"])))
        g.add((quote_sel, RDF.type, OA.TextQuoteSelector))
        g.add((quote_sel, OA.exact, Literal(sel["exact"])))
        g.add((quote_sel, OA.prefix, Literal(sel["prefix"])))
        g.add((quote_sel, OA.suffix, Literal(sel["suffix"])))
        g.add((pos_sel, RDF.type, OA.TextPositionSelector))
        g.add((pos_sel, OA.start, Literal(sel["start"], datatype=XSD.nonNegativeInteger)))
        g.add((pos_sel, OA.end, Literal(sel["end"], datatype=XSD.nonNegativeInteger)))

    summary = json.loads((run.root / ATTACH_FILE).read_bytes()) if (run.root / ATTACH_FILE).is_file() else None
    if summary is not None:  # an attach step over no facts has no records, but it made answer.json
        attach_times += [summary["started_at"], summary["ended_at"]]
    if attach_times:
        g.add((attach, RDF.type, PROV.Activity))
        g.add((attach, RDF.type, OURS.AttachStep))
        g.add((attach, DCTERMS.isPartOf, run_node))
        g.add((attach, PROV.wasAssociatedWith, agent("main")))
        g.add((attach, PROV.startedAtTime, Literal(min(attach_times), datatype=XSD.dateTime)))
        g.add((attach, PROV.endedAtTime, Literal(max(attach_times), datatype=XSD.dateTime)))

    _add_kg(g, iri, kgraph, claims)
    if run.answer.is_file():
        _add_answer(g, iri, json.loads(run.answer.read_text(encoding="utf-8")))
        _add_answer_source(g, iri, records, summary)
    return g


ANSWER_SOURCES = {"answer_from_draft": "draft", "no_final_answer": "none"}  # coverage reason -> answerSource


def answer_source(records: list[dict[str, Any]]) -> tuple[str, dict[str, Any] | None]:
    """How answer.json came about: (final_answer | draft | none, the record that made it), or ("unknown", None).

    Only the main agent's research records count: attach-step, batch and subagent records do not
    make the run's answer.
    """
    for rec in reversed(records):
        meta = rec.get("custom_metadata") or {}
        if rec["agent_id"] != "main" or meta.get("origin", "research") != "research":
            continue
        if rec["subtype"] == "ai_model_invocation" and meta.get("final_answer"):
            return "final_answer", rec
        if rec["subtype"] == "coverage" and rec["generated"].get("reason") in ANSWER_SOURCES:
            return ANSWER_SOURCES[rec["generated"]["reason"]], rec
    return "unknown", None


def _add_answer_source(g: Graph, iri: Iris, records: list[dict[str, Any]],
                       attach_summary: dict[str, Any] | None) -> None:
    """How the research answer came about, and with an attach step what made answer.json from it.

    Without an attach step the research answer is answer.json. With one, answer.json is the
    attach step's rewrite (every fact origin attach): it is generated by the attach activity and
    derived from an `answer-research` entity (answer.research.json, with the sha256 attach.json
    recorded), which is what the final-answer call or the draft made. ours:answerSource on both
    names the research answer's source, so a query need not know whether the run had an attach step.
    """
    source, rec = answer_source(records)
    node = iri("answer")
    g.add((node, OURS.answerSource, Literal(source)))
    made = node
    if attach_summary is not None:
        made = iri("answer-research")
        attach = iri("activity", "attach")
        for t in (PROV.Entity, OURS.Answer):
            g.add((made, RDF.type, t))
        g.add((made, OURS.answerSource, Literal(source)))
        g.add((made, OURS.fileName, Literal(ANSWER_BEFORE)))
        g.add((made, OURS.sha256, Literal(attach_summary["answer_research_sha256"])))
        g.add((node, PROV.wasGeneratedBy, attach))
        g.add((node, PROV.wasDerivedFrom, made))
        g.add((attach, PROV.used, made))
    if rec is None:  # no model call and no harness record made it (a run built by hand)
        return
    act = iri("task", rec["task_id"])
    g.add((made, PROV.wasGeneratedBy, act))
    draft = (rec["generated"].get("detail") or {}).get("draft") if source == "draft" else None
    if draft:  # no model call made this answer: the harness took it from the agent's draft file
        entity = iri("draft")
        g.add((entity, RDF.type, PROV.Entity))
        g.add((entity, RDF.type, OURS.AnswerDraft))
        g.add((entity, OURS.fileName, Literal(draft.get("copy", draft["file"]))))  # the copy the sandbox cannot change
        g.add((entity, OURS.sourceFile, Literal(draft["file"])))
        g.add((entity, OURS.sha256, Literal(draft["sha256"])))
        g.add((act, PROV.used, entity))
        g.add((made, PROV.wasDerivedFrom, entity))


def _add_kg(g: Graph, iri: Iris, kgraph: dict[str, Any], claims: dict[str, URIRef]) -> None:
    for node in kgraph["nodes"]:
        subject = node_iri(node["id"])
        g.add((subject, RDF.type, OURS.Paper if node["kind"] == "paper" else OURS.Entity))
        g.add((subject, RDFS.label, Literal(node["label"])))
    for edge in kgraph["edges"]:
        e = iri("edge", edge["id"])
        s = node_iri(edge["source"])
        p = URIRef(edge["predicate"]["iri"])
        o = node_iri(edge["target"]) if edge["target"] is not None else _value(edge["literal"])
        g.add((s, p, o))  # the knowledge graph triple itself
        for t in (PROV.Entity, RDF.Statement, OURS.KGEdge):
            g.add((e, RDF.type, t))
        g.add((e, OURS.edgeId, Literal(edge["id"])))
        g.add((e, RDF.subject, s))
        g.add((e, RDF.predicate, p))
        g.add((e, RDF.object, o))
        g.add((e, OURS.predicateText, Literal(edge["predicate"]["text"])))
        g.add((e, OURS.origin, Literal(edge["origin"])))
        g.add((e, PROV.wasDerivedFrom, claims.get(edge["claim"], iri("claim", edge["claim"]))))
        if edge["evidence"]["paper"]:
            g.add((corpus_file(edge["evidence"]["file"]), OURS.paper, node_iri(f"paper:{edge['evidence']['paper']}")))


def _add_answer(g: Graph, iri: Iris, answer: dict[str, Any]) -> None:
    node = iri("answer")
    g.add((node, RDF.type, PROV.Entity))
    g.add((node, RDF.type, OURS.Answer))
    g.add((node, OURS.conceptSha256, Literal(answer["concept_sha256"])))
    for row in answer["rows"]:
        for fact in row["facts"]:
            f = iri("fact", fact["id"])
            g.add((f, RDF.type, PROV.Entity))
            g.add((f, RDF.type, OURS.AnswerFact))
            g.add((f, OURS.factId, Literal(fact["id"])))
            g.add((f, OURS.rowId, Literal(row["id"])))
            g.add((f, OURS.origin, Literal(fact["origin"])))
            for field in ("s", "p", "o"):
                g.add((f, OURS[field], _value(fact[field])))
            g.add((f, DCTERMS.isPartOf, node))
            for claim_id in fact["claims"]:
                g.add((f, PROV.wasDerivedFrom, iri("claim", claim_id)))


def serialize(g: Graph) -> bytes:
    data = g.serialize(format="turtle", encoding="utf-8")
    return data.replace(b"\r\n", b"\n")


def write(run: RunDir) -> tuple[Path, Graph]:
    g = build(run)
    path = run.root / TTL_FILE
    path.write_bytes(serialize(g))
    return path, g


def load(run: RunDir) -> Graph:
    g = Graph()
    g.parse(run.root / TTL_FILE, format="turtle")
    return g
